# Generate the 600-cell orbit
def quaternion_multiply(q1, q2):
    a1, b1, c1, d1 = q1
    a2, b2, c2, d2 = q2
    return np.array([
        a1*a2 - b1*b2 - c1*c2 - d1*d2,
        a1*b2 + b1*a2 + c1*d2 - d1*c2,
        a1*c2 - b1*d2 + c1*a2 + d1*b2,
        a1*d2 + b1*c2 - c1*b2 + d1*a2
    ])

vertices = []
current = np.array([1, 0, 0, 0])
vertices.append(current)

group_set = set()
group_set.add(tuple(np.round(current, 10)))

generators = [g1, g2, g3]
for _ in range(50):
    new_verts = []
    for v in vertices:
        for g in generators:
            v_new = quaternion_multiply(g, v)
            v_new = v_new / np.linalg.norm(v_new)
            if tuple(np.round(v_new, 10)) not in group_set:
                group_set.add(tuple(np.round(v_new, 10)))
                new_verts.append(v_new)
    if len(new_verts) == 0:
        break
    vertices.extend(new_verts)

vertices = np.array(vertices)
